"""税种口径：全系统唯一的税种名单 + 从文本里识别税种。

为什么单独抽一个模块：
  采集侧（给法规打税种标签）和检索侧（从用户问题里推断税种，用于加过滤）
  必须用同一份名单。两处各写一份，迟早会出现"采集标了、检索认不出"的错位，
  而这正是 2026-09-30 那批数据出问题的形态。

识别规则只有一条但很关键：**长名优先，命中后从文本里挖掉**。
否则"土地增值税"会被"增值税"先匹配走，把用户问的土地增值税
过滤成增值税，召回一堆不相干的条文。
"""

from __future__ import annotations

# 按本项目口径的税种名单。
#
# 允许带"发票""会计""社会保险费""残疾人就业保障金"这类非税种类目：
# 它们在财税实务里是独立的检索维度，客户就是按这些词来问的
# （"发票丢了怎么办""社保费怎么缴""残保金怎么算"）。
# 字段名仍叫 tax_types，是因为它在检索里扮演的角色就是"税种过滤维度"，
# 改名的收益不抵迁移成本。
TAX_TYPES: tuple[str, ...] = (
    "残疾人就业保障金",
    "社会保险费",
    "城市维护建设税",
    "个人所得税",
    "企业所得税",
    "土地增值税",
    "城镇土地使用税",
    "车辆购置税",
    "耕地占用税",
    "环境保护税",
    "船舶吨税",
    "烟叶税",
    "增值税",
    "消费税",
    "印花税",
    "房产税",
    "契税",
    "资源税",
    "车船税",
    "关税",
    "发票",
    "会计",
)

# 长名优先的匹配顺序（"城镇土地使用税"要先于"土地使用税"之类不存在的情况也无妨，
# 关键是先于"增值税"这类短名的子串关系）
_BY_LENGTH_DESC: tuple[str, ...] = tuple(sorted(TAX_TYPES, key=len, reverse=True))

# 挖空用的占位符。用一个正常文本里不会出现的字符，避免替换后把别的词拼在一起。
_FILLER = "\u3000"


def detect_tax_types(text: str) -> list[str]:
    """从一段文本里识别税种，返回按出现顺序去重的结果。

    同一段文本里提到多个税种就都返回——用户问"小微企业有什么优惠"时
    确实同时涉及增值税和企业所得税。
    """

    if not text:
        return []

    remaining = text
    found: list[str] = []
    for name in _BY_LENGTH_DESC:
        if name in remaining:
            found.append(name)
            # 挖掉已匹配的部分，防止"增值税"再吃"土地增值税"的末尾
            remaining = remaining.replace(name, _FILLER * len(name))

    # 按在原文里出现的位置排序，让返回顺序稳定、可读
    return sorted(found, key=lambda name: text.find(name))
